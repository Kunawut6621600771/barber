INSERT INTO barber_services (barber_id, service_id)
SELECT b.id, s.id
  FROM barbers b
  CROSS JOIN services s
  LEFT JOIN service_categories c ON c.id = s.category_id
 WHERE b.code = 'BB-03'
    OR (b.code IN ('BB-01','BB-02')
        AND COALESCE(c.name, '') NOT IN ('ทำสีผม', 'ดัด/ยืดผม')
        AND s.name NOT IN ('แพ็กเกจเจ้าบ่าว', 'ย้อมสีหนวดเครา'))
ON CONFLICT DO NOTHING;

